export type Pt = [number, number];
/** Face TL, TR, BR, BL in source video pixels (TL->TR is the face's top edge). */
export type Quad = [Pt, Pt, Pt, Pt];

export type SeatId = "seat1" | "seat2" | "seat3";
export type Slot = SeatId | "up" | "hole";
export type ClipKind = "idle" | "deal" | "wait" | "reveal" | "hold" | "discard" | "hit" | "bridge";

/** A physical card visible during a clip; frames are clip-relative (may lie outside the clip). */
export interface FootageCard {
  slot: Slot;
  /** 1-based position in its hand (dealer: up = 1, hole = 2). */
  index: number;
  in: number;
  out: number;
  flip: number | null;
  faceDown: boolean;
  quad: Quad;
  /** Outline per frame while the dealer slides it in face up: quads[i] is frame from + i, up to `in`. */
  path?: { from: number; quads: Quad[] };
  /** Times it is lifted off its resting place and put back (the up card scooping the hole card over):
   *  over [from, to) its outline is quads[i] at frame from + i while it could be followed, else none. */
  trips?: { from: number; to: number; quads: Quad[] }[];
  /** The pile its hand is gathered into, when this card is the one on top: quads[i] (null where
   *  it couldn't be fitted) at frame from + i; the face rides on it to the tray. */
  pile?: { from: number; quads: (Quad | null)[] };
  /** From the frame it starts to be swept up: its outline while it moves on its own (quads[i] is frame from + i), then none. */
  away?: { from: number; quads: Quad[] };
  /**
   * A hit card as it comes down onto the hand, tracked back from where it comes to rest (the
   * pipeline's landing pass, SAM 2), frame by frame from `from`: its outline (convex; none before it
   * is in view), which tells it from the card it lands on, white on white, and the four corners of
   * its face as it comes down tilted under her finger. From `rest` it lies on its resting outline.
   */
  land?: { from: number; outlines: (Pt[] | null)[]; faces: (Quad | null)[]; rest: number };
}

export interface ClipInfo {
  file: string;
  kind: ClipKind;
  frames: number;
  sourceStart: number;
  cards: FootageCard[];
  loop?: string;
  loopFrames?: number;
  /** The loop plays only clip frames loopFrom..loopTo-1 (an idle's calm stretch); absent = the whole clip. */
  loopFrom?: number;
  loopTo?: number;
  still: number;
  mask?: string;
  seat?: SeatId;
  card?: number;
  part?: number;
  /** A bridge clip: the generated frames between `from` at clip frame `at` and `to`'s first frame. */
  bridge?: { from: string; at: number; to: string };
  /**
   * A discard: the clip frame her hand first comes over each hand's cards on the approach that
   * lifts them, for every hand size the take doesn't hold (seat: 3-6 cards, the real two plus
   * the rest laid in; dealer: 1-5 graphic draws). The laid-in cards are gone by then.
   */
  reach?: Partial<Record<SeatId | "dealer", Record<string, number>>>;
}

/**
 * An interpolated move between two clips that were not filmed back to back
 * (game_assets/bridges.json, written by the pipeline's bridges pass). Leaving
 * `from` on clip frame `at`, then playing `frames` generated frames, lands on
 * `to`'s first frame. `frames` 0 means the two frames already match: a cut.
 */
export interface Bridge {
  name: string;
  from: string;
  at: number;
  to: string;
  file: string | null;
  frames: number;
  class: "cut" | "short" | "long" | "generative";
  critical: boolean;
  /** tool: generated by the interpolation app; flow: the optical-flow stand-in (none generated yet, or rejected). */
  source: "tool" | "flow";
  /** Set when a generated bridge for this row was rejected on review (its note, if any). */
  rejected?: string | true;
}

export interface Plate {
  clip: string;
  frame: number;
  cards: Quad[];
}

export interface Manifest {
  fps: number;
  width: number;
  height: number;
  seats: SeatId[];
  playOrder: SeatId[];
  masks: string;
  dealer: { up: Quad; hole: Quad; shoe: Pt; discardTray: Pt };
  plates: Record<SeatId, Record<string, Plate>>;
  clips: Record<string, ClipInfo>;
}

/** game_assets/ is the dev server's public dir (see vite.config.ts). */
export const ASSET_BASE = "/";

export async function loadManifest(): Promise<Manifest> {
  const r = await fetch(`${ASSET_BASE}manifest.json`);
  if (!r.ok) throw new Error(`manifest.json: HTTP ${r.status} — run the pipeline first (see README)`);
  return r.json();
}

/**
 * Bridges join the manifest as clips of kind "bridge" (so the player and loader treat them like
 * any footage) and are indexed by the clip they leave from. No bridges file: none, every cut is hard.
 */
export async function loadBridges(m: Manifest): Promise<Map<string, Bridge[]>> {
  const byFrom = new Map<string, Bridge[]>();
  const r = await fetch(`${ASSET_BASE}bridges.json`).catch(() => null);
  if (!r?.ok) return byFrom;
  const { bridges } = (await r.json()) as { bridges: Bridge[] };
  for (const b of bridges) {
    if (!m.clips[b.from] || !m.clips[b.to]) continue;
    // a row that says it has frames but names no file can't be played: leave it out
    if (b.frames > 0 && !b.file) continue;
    if (b.frames > 0 && b.file) {
      m.clips[b.name] = {
        file: b.file, kind: "bridge", frames: b.frames, cards: [], still: 0,
        // never a natural successor of anything
        sourceStart: -1e9,
        bridge: { from: b.from, at: b.at, to: b.to },
      };
    }
    const list = byFrom.get(b.from) ?? [];
    list.push(b);
    byFrom.set(b.from, list);
  }
  return byFrom;
}

/** Footage cards of one slot that are on the table at a clip frame. */
export const cardsAt = (clip: ClipInfo, slot: Slot, frame: number) =>
  clip.cards.filter((c) => c.slot === slot && c.in <= frame && frame < c.out);

/** First clip frame the card shows its face up: where its slide-in path starts, else where it lands. */
export const faceFrom = (c: FootageCard) => (c.path?.quads.length ? c.path.from : faceUp(c));

/** First clip frame the card lies face up where it rests: its landing, or the hole card's flip (never, unflipped). */
const faceUp = (c: FootageCard) => (c.faceDown ? (c.flip === null ? Infinity : Math.max(c.in, c.flip)) : c.in);

/** Frame the card's face stops showing: when it is no longer followed after leaving its resting place. */
export const faceUntil = (c: FootageCard) =>
  c.pile ? c.pile.from + c.pile.quads.length : c.away ? c.away.from + c.away.quads.length : c.out;

/** The card's outline at a clip frame while it is face up on screen (sliding in, lying, being swept off), else null. */
export function faceQuadAt(c: FootageCard, frame: number): Quad | null {
  if (c.pile && frame >= c.pile.from) return c.pile.quads[frame - c.pile.from] ?? null;
  if (c.away && frame >= c.away.from) return c.away.quads[frame - c.away.from] ?? null;
  if (frame >= c.out) return null;
  const landed = c.land && frame < c.land.rest ? c.land.faces[frame - c.land.from] : undefined;
  if (landed) return landed;
  const trip = c.trips?.find((t) => frame >= t.from && frame < t.to);
  if (trip) return trip.quads[frame - trip.from] ?? null;
  if (frame >= faceUp(c)) return c.quad;
  const i = c.path ? frame - c.path.from : -1;
  return c.path && i >= 0 && i < c.path.quads.length ? c.path.quads[i] : null;
}

/** The clip frames a loop file ping-pongs over: from, from + 1, ..., from + n - 1 and back. */
export const loopSpan = (c: ClipInfo) => {
  const from = c.loopFrom ?? 0;
  return { from, n: (c.loopTo ?? c.frames) - from };
};

/** Clip names, by the conventions the pipeline writes. */
export const clipName = {
  openingIdle: "opening_idle",
  deal: (mask: string) => `${mask}_deal`,
  wait: (mask: string) => `${mask}_wait`,
  reveal: (mask: string) => `${mask}_reveal`,
  hold: (mask: string) => `${mask}_hold`,
  discard: (mask: string) => `${mask}_discard`,
  idle: (mask: string) => `${mask}_idle`,
  hit: (seat: SeatId, card: number) => `${seat}_card${card}_deal`,
  hitWait: (seat: SeatId, card: number) => `${seat}_card${card}_wait`,
};

/** The clip that follows `name` in the original take, if any (a seamless continuation). */
export function naturalNext(m: Manifest, name: string): string | undefined {
  const c = m.clips[name];
  const end = c.sourceStart + c.frames;
  return Object.keys(m.clips).find((k) => m.clips[k].sourceStart === end);
}
