"""Pass 5: the manifest the app plays from, plus the seat compositing masks.

For every clip: the physical cards visible during it (clip-relative frames
for landing, flip and pickup; outline quads; which seat and which card of
that seat's hand), so the app can put a face on every card and knows how
many cards each seat shows at any moment.

Plates: for each seat and each hand size the game can need (0, 2-6), a clip
frame where that seat shows exactly that many cards and nothing covers it.
The app grabs these frames from the clips at load time with the same video
decoder that plays the footage, so a plate and the live frame it is laid
into can never differ in colour.
"""

import json
import sys
from pathlib import Path

import cv2
import numpy as np

from bj3.edl import clusters
from bj3.export import clip_path, loop_path, STATIC
from bj3.geometry import PLAY_ORDER, SEATS

W, H = 1440, 810


def seat_masks(cards: list[dict], out: Path) -> None:
    img = np.zeros((H, W, 3), np.uint8)
    for ch, seat in zip((2, 1, 0), SEATS):  # PNG stores RGB; cv2 writes BGR
        m = np.zeros((H, W), np.uint8)
        for c in cards:
            if c["region"] == seat:
                cv2.fillConvexPoly(m, np.array(c["quad"], np.float32).round().astype(np.int32), 255)
        m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (11, 11)))
        m = cv2.GaussianBlur(m, (7, 7), 2.0)
        img[..., ch] = m
    out.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out), img)


KIND_NOTE = {
    "idle": "empty table, betting loop",
    "deal": "starting hands dealt",
    "wait": "decision pause",
    "reveal": "hole card flipped",
    "hold": "pause after the reveal",
    "discard": "cards picked up",
    "hit": "one card dealt",
}


def write_index(segs: list[dict], clips: dict, fps: float, path: Path) -> None:
    """A human index of every clip: what it shows and where it came from in the take."""
    tc = lambda f: f"{int(f / fps // 60)}:{f / fps % 60:05.2f}"
    lines = [
        "# Clip index",
        "",
        "Generated by `python -m bj3` from `full_footage.mp4`. Do not edit by hand.",
        "",
        "Seat masks read left to right as seen on screen: `101` = seats 1 and 3 taken, seat 2 empty.",
        "The dealer deals and plays seats right to left (seat 3 first).",
        "",
        "Every *wait*, *hold* and *idle* clip also has a ping-pong loop in `loops/` (forward then",
        "reversed, so it can run for any decision time without a visible jump).",
        "",
    ]
    groups = [
        ("Part 1 — starting hands, one cycle per seat combination", lambda s: s.get("part") == 1 or s["name"] == "opening_idle"),
        ("Part 2 — full table, hits up to six cards per seat", lambda s: s.get("part") == 2),
    ]
    for title, pred in groups:
        lines += [f"## {title}", "", "| Clip | Shows | Source in → out | Length | Loop |", "|---|---|---|---|---|"]
        for s in segs:
            if not pred(s):
                continue
            c = clips[s["name"]]
            what = KIND_NOTE[s["kind"]]
            if s["kind"] == "hit" or (s.get("seat") and s["kind"] == "wait"):
                what = f"seat {s['seat'][-1]}, card {s['card']}: " + what
            elif s.get("mask"):
                what = f"seats `{s['mask']}`: " + what
            loop = f"`{c['loop']}`" if c.get("loop") else ""
            lines.append(f"| `{c['file']}` | {what} | {tc(s['start'])} → {tc(s['end'])} | {s['seconds']:.2f}s | {loop} |")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def build(cards_json: str, edl_json: str, pose_npz: str, out_dir: str) -> None:
    out = Path(out_dir)
    cards = json.load(open(cards_json))["cards"]
    edl = json.load(open(edl_json))
    fps = edl["fps"]
    segs = edl["segments"]

    # index of each card within its seat's hand (dealer: up = 1, hole = 2)
    for g in clusters(cards):
        for seat in SEATS:
            for i, c in enumerate(sorted([c for c in g if c["region"] == seat], key=lambda c: c["birth"])):
                c["index"] = i + 1
        for c in g:
            if c["region"] == "up":
                c["index"] = 1
            if c["region"] == "hole":
                c["index"] = 2

    z = np.load(pose_npz)
    P = z["pose"].astype(np.float32)
    keep = z["keep"]
    motion = np.zeros(len(P), np.float32)
    motion[1:] = np.abs(P[1:] - P[:-1])[:, keep].mean(1)

    clips = {}
    for s in segs:
        a, b = s["start"], s["end"]
        visible = []
        for c in cards:
            if c["birth"] < b and c["death"] > a:
                visible.append({
                    "slot": c["region"], "index": c["index"],
                    "in": c["birth"] - a, "out": c["death"] - a,
                    "flip": None if c["flip"] is None else c["flip"] - a,
                    "faceDown": c["face_down"],
                    "quad": c["quad"],
                })
        visible.sort(key=lambda v: (v["slot"], v["index"]))
        entry = {
            "file": clip_path(s), "kind": s["kind"], "frames": s["frames"],
            "sourceStart": a, "cards": visible,
        }
        for k in ("mask", "seat", "card", "part"):
            if k in s:
                entry[k] = s[k]
        if s["kind"] in STATIC and s["frames"] >= 3:
            entry["loop"] = loop_path(s)
            entry["loopFrames"] = 2 * s["frames"] - 2
        # the stillest frame: where plates are grabbed and where a still is shown if needed
        entry["still"] = int(np.argmin(motion[a:b]))
        clips[s["name"]] = entry

    def plate(clip_name, seat):
        c = clips[clip_name]
        f = c["still"]
        quads = [v["quad"] for v in c["cards"] if v["slot"] == seat and v["in"] <= f < v["out"]]
        return {"clip": clip_name, "frame": f, "cards": quads}

    plates = {}
    for seat in SEATS:
        plates[seat] = {"0": plate("full_table_idle", seat), "2": plate("full_table_wait", seat)}
        for n in range(3, 7):
            plates[seat][str(n)] = plate(f"{seat}_card{n}_wait", seat)
        for n, p in plates[seat].items():
            assert len(p["cards"]) == int(n), (seat, n, len(p["cards"]))

    def median_quad(slot):
        qs = np.array([c["quad"] for c in cards if c["region"] == slot], np.float32)
        return np.median(qs, axis=0).round(2).tolist()

    seat_masks(cards, out / "masks" / "seats.png")
    manifest = {
        "version": 1,
        "source": "full_footage.mp4",
        "fps": fps,
        "width": W, "height": H,
        "seats": list(SEATS),
        "playOrder": list(PLAY_ORDER),
        "masks": "masks/seats.png",
        "dealer": {
            "up": median_quad("up"),
            "hole": median_quad("hole"),
            "shoe": [985, 374],
            "discardTray": [508, 392],
        },
        "plates": plates,
        "clips": clips,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1))
    write_index(segs, clips, fps, out / "CLIPS.md")
    print(f"manifest: {len(clips)} clips, plates for {len(plates)} seats -> {out / 'manifest.json'}")


if __name__ == "__main__":
    build(*sys.argv[1:])
